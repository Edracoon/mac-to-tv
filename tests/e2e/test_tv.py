restore, servers, cleanup = [], [], []
fake = movies = base = files = h264 = None


def swap(obj, **attrs):
    """Sets attributes for the time of these tests."""
    for k, v in attrs.items():
        restore.append((obj, k, getattr(obj, k)))
        setattr(obj, k, v)


def serve(handler):
    httpd = ThreadingHTTPServer(("127.0.0.1", 0), handler)
    httpd.daemon_threads = True
    threading.Thread(target=httpd.serve_forever, daemon=True).start()
    servers.append(httpd)
    return f"http://127.0.0.1:{httpd.server_port}"


def setUpModule():
    global fake, movies, base, files, h264
    if not (shutil.which("ffmpeg") and shutil.which("ffprobe")):
        raise unittest.SkipTest("ffmpeg and ffprobe are needed")
    tmp = Path(tempfile.mkdtemp(prefix="mac-to-tv-tests-"))
    cleanup.append(lambda: shutil.rmtree(tmp, ignore_errors=True))
    movies = (tmp / "movies").resolve()
    movies.mkdir()
    # 30 s, small, silent. MPEG-4 + AAC: a file the TV decodes. With FLAC sound: the sound has to be converted.
    clip = ["ffmpeg", "-v", "error", "-f", "lavfi", "-i", "testsrc=size=320x180:rate=25", "-f", "lavfi", "-i", "anullsrc=r=44100:cl=stereo",
            "-t", "30", "-c:v", "mpeg4", "-q:v", "8"]
    subprocess.run(clip + ["-c:a", "aac", "-movflags", "+faststart", str(movies / "plain.mp4")], check=True)
    subprocess.run(clip + ["-c:a", "flac", str(movies / "flac.mkv")], check=True)
    for encoder in ("libx264", "h264_videotoolbox"):  # H.264 + AAC, what a browser reads as is: only where ffmpeg can make it
        made = subprocess.run(clip[:-4] + ["-c:v", encoder, "-pix_fmt", "yuv420p", "-c:a", "aac", "-movflags", "+faststart", str(movies / "h264.mp4")], capture_output=True)
        if not made.returncode:
            h264 = movies / "h264.mp4"
            break
    (movies / "lines.srt").write_text("".join(f"{n}\n00:00:{n * 2:02},000 --> 00:00:{n * 2 + 1:02},500\nLine {n}\n\n" for n in range(1, 14)))

    # the server: its files in the temporary folder, its launch check after 1 s instead of 12
    quiet = open(os.devnull, "w")  # the server logs every request of the TV
    cleanup.append(quiet.close)
    swap(sys, stdout=quiet)
    swap(server, MEDIA_DIR=movies)
    swap(server.config, path=tmp / "config.json")
    swap(server.progress, path=tmp / "progress.json", films={})
    swap(server.stats, path=tmp / "stats.json", data={}, last=None)
    swap(sources.history, path=tmp / "history.json")
    swap(server.TVPlayer, START_CHECK=1)
    base = serve(server.Handler)
    swap(server, PORT=int(base.rsplit(":", 1)[1]))
    files = serve(functools.partial(type("Quiet", (SimpleHTTPRequestHandler,), {"log_message": lambda *a: None}), directory=str(movies)))

    # the TV: picked by the address of its description, as discovery would after finding it
    fake = FakeTV()
    tv = tvlib.TV("127.0.0.1")
    tv.load(tvlib.summarize([tvlib.describe(fake.location)]))
    swap(server.tv_player, tv=tv)


def tearDownModule():
    for httpd in servers:
        httpd.shutdown()
        httpd.server_close()
    if fake:
        fake.close()
    for obj, k, v in reversed(restore):
        setattr(obj, k, v)
    for fn in cleanup:
        fn()


def api(path, body=None):
    """→ (HTTP status, answer). GET without a body, POST with one."""
    req = urllib.request.Request(f"{base}/api/{path}", None if body is None else json.dumps(body).encode(), {"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            return r.status, json.load(r)
    except urllib.error.HTTPError as e:
        with e:
            return e.code, json.load(e)


def status():
    return api("status")[1]


def wait(what, check, timeout=15):
    end = time.time() + timeout
    while not (found := check()):
        if time.time() > end:
            raise AssertionError("timed out waiting for " + what)
        time.sleep(0.1)
    return found


def can_burn_subtitles():
    try:
        out = subprocess.run([server.FFMPEG_SUBS, "-hide_banner", "-filters"], capture_output=True, text=True).stdout
        enc = subprocess.run([server.FFMPEG_SUBS, "-hide_banner", "-encoders"], capture_output=True, text=True).stdout
        return " subtitles " in out and "h264_videotoolbox" in enc
    except OSError:
        return False


class OnTheFakeTV(unittest.TestCase):
    def setUp(self):
        api("transport", {"action": "stop"})
        fake.reset()
        server.tv_player.job = server.Launches()
        server.progress.films.clear()
        server.stats.data.clear()
        server.stats.last = None

    def test_a_file_is_played_paused_sought_and_stopped(self):
        fake.duration = 30
        self.assertEqual(api("cast", {"path": str(movies / "plain.mp4")}), (200, {"title": "plain"}))
        self.assertEqual(fake.calls[:3], ["Stop", "SetAVTransportURI", "Play"])
        self.assertEqual(fake.fetches[:2], [("HEAD", None, 200), ("GET", "bytes=0-", 206)])
        wait("the whole file to be read", lambda: fake.received == (movies / "plain.mp4").stat().st_size)
        st = status()
        self.assertEqual((st["CurrentTransportState"], st["title"], st["TrackDuration"]), ("PLAYING", "plain", "0:00:30"))
        self.assertNotIn("TrackURI", st)  # the address of the video is for the TV only
        self.assertEqual(api("job")[1], {"busy": False, "title": "plain.mp4", "steps": [["Starting the TV", ""]], "error": "", "detail": ""})

        api("transport", {"action": "pause"})
        self.assertEqual(status()["CurrentTransportState"], "PAUSED_PLAYBACK")
        api("transport", {"action": "play"})
        self.assertEqual(status()["CurrentTransportState"], "PLAYING")

        self.assertEqual(api("transport", {"action": "seek", "seconds": 12})[0], 200)
        self.assertIn(secs(status()["RelTime"]), (12, 13))
        method, rng, code = fake.fetches[-1]
        self.assertEqual((method, code), ("GET", 206))
        self.assertGreater(int(rng[6:-1]), 0)  # the TV asked for the middle of the file, and got it

        api("volume", {"value": 25})
        self.assertEqual(status()["CurrentVolume"], "25")

        address = fake.uri
        api("transport", {"action": "stop"})
        self.assertEqual(fake.state, "STOPPED")
        with self.assertRaises(urllib.error.HTTPError) as gone:  # stopped: nothing is served any more
            urllib.request.urlopen(address, timeout=5)
        self.assertEqual(gone.exception.code, 404)
        gone.exception.close()

    def test_a_format_the_tv_cannot_decode_goes_through_a_stream_that_keeps_its_position(self):
        fake.lag = 2  # after a new address, the TV reports the previous one for 2 s
        self.assertEqual(api("cast", {"path": str(movies / "flac.mkv")}), (200, {"title": "flac"}))
        self.assertTrue(fake.uri.endswith("/stream.ts"), fake.uri)
        wait("the stream to arrive", lambda: fake.received > 10_000)
        st = status()
        self.assertEqual((st["CurrentTransportState"], st["title"], st["TrackDuration"]), ("PLAYING", "flac", "0:00:30"))  # the TV does not know the length of a stream: we do
        wait("the TV to report the stream", lambda: secs(status()["RelTime"]) >= 3)

        # seeking a stream = restarting it from there. While the TV still reports the old stream, the position is the
        # point asked for, not the old stream's counter (which sent the movie back to its start)
        self.assertEqual(api("transport", {"action": "seek", "seconds": 15})[0], 200)
        self.assertEqual(status()["RelTime"], "0:00:15")
        wait("the TV to report the new stream", lambda: 17 <= secs(status()["RelTime"]) <= 25)
        self.assertEqual(fake.calls.count("SetAVTransportURI"), 2)
        self.assertNotIn("Seek", fake.calls)

    @unittest.skipUnless(can_burn_subtitles(), "needs ffmpeg-full (subtitles filter) and the macOS hardware encoder")
    def test_subtitle_delay_changed_twice_in_a_row_keeps_the_position(self):
        fake.lag = 1
        self.assertEqual(api("cast", {"path": str(movies / "plain.mp4"), "burn": str(movies / "lines.srt")})[0], 200)
        self.assertEqual(status()["subDelay"], 0)
        api("transport", {"action": "seek", "seconds": 10})
        self.assertEqual(api("subdelay", {"delta": 0.5}), (200, {"subDelay": 0.5}))
        self.assertEqual(api("subdelay", {"delta": 0.5}), (200, {"subDelay": 1.0}))
        st = status()
        self.assertEqual(st["subDelay"], 1.0)
        self.assertIn(secs(st["RelTime"]), range(10, 16))
        wait("the burned-in stream to arrive", lambda: fake.received > 10_000)

    def test_a_tv_that_stops_right_away_is_reported(self):
        fake.stops_at_once = True
        self.assertEqual(api("cast", {"path": str(movies / "plain.mp4")})[0], 200)
        wait("the failure to show", lambda: api("job")[1]["error"].startswith("The TV stopped right away"), timeout=8)

    def test_a_refused_file_never_reaches_the_tv(self):
        code, out = api("cast", {"path": "/etc/hosts"})
        self.assertEqual(code, 400)
        self.assertEqual(api("job")[1]["error"], "This file is outside the movies folder.")
        self.assertEqual(fake.calls, [])

    def test_a_catalog_movie_resumes_and_its_position_is_recorded(self):
        fake.duration = 30
        play = {"url": f"{files}/plain.mp4", "title": "Film", "film": {"id": "tt1"}, "start": 8}
        self.assertEqual(api("play", play), (200, {"title": "Film"}))
        self.assertIn("Seek", fake.calls)
        self.assertEqual([s[0] for s in api("job")[1]["steps"]], ["Checking the format", "Starting the TV", "Resuming at 0:00:08"])
        self.assertEqual(fake.fetches[1][2], 200)  # relayed from the address of the source
        server.tv_player.record()  # what the server does every 10 s
        film = api("progress")[1]["films"][0]
        self.assertEqual((film["id"], film["duration"]), ("tt1", 30))
        self.assertIn(film["position"], range(8, 12))
        self.assertEqual(api("stats")[1]["plays"], {"movies": 1})

    def test_playing_in_the_browser_sends_nothing_to_the_tv(self):
        if not h264:
            self.skipTest("this ffmpeg has no H.264 encoder to make the clip")
        code, got = api("watch", {"kind": "file", "path": str(h264)})  # H.264 + AAC in MP4: served as a file, with Range
        self.assertEqual((code, got["direct"], got["title"]), (200, True, "h264"))
        req = urllib.request.Request(f"{base}/watch/{got['token']}/file", headers={"Range": "bytes=0-99"})
        with urllib.request.urlopen(req, timeout=10) as r:
            self.assertEqual((r.status, len(r.read())), (206, 100))
        subprocess.run(["ffmpeg", "-v", "error", "-i", str(h264), "-c:v", "copy", "-c:a", "flac", str(movies / "h264flac.mkv")], check=True)
        code, got = api("watch", {"kind": "file", "path": str(movies / "h264flac.mkv")})  # anything else: a converted stream
        self.assertEqual((code, got["direct"]), (200, False))
        with urllib.request.urlopen(f"{base}/watch/{got['token']}/stream?t=0", timeout=20) as r:
            self.assertIn(b"ftyp", r.read(64))  # fragmented MP4
        self.assertEqual(api("watchjob")[1]["steps"], [["Checking the format", ""], ["Converting for the browser", "FLAC audio"]])
        self.assertEqual(api("unwatch", {"token": got["token"], "position": 3})[0], 200)
        self.assertIsNone(server.browser.current())
        self.assertEqual(fake.calls, [])


class Discovery(unittest.TestCase):
    def test_the_fake_tv_is_found_on_the_network_and_seen_as_compatible(self):
        try:
            other = FakeTV(ssdp=True)
        except OSError as e:
            self.skipTest(f"the discovery port cannot be shared here ({e})")
        try:
            try:
                found = tvlib.ssdp(1.5)
            except OSError as e:
                self.skipTest(f"no network to search ({e})")
            if not any(other.location in locations for locations in found.values()):
                self.skipTest("multicast does not come back to this machine here")
            mine = [t for t in tvlib.discover(1.5) if t["name"] == "Fake TV"]
            self.assertTrue(mine and mine[0]["compatible"], mine)
            self.assertEqual(mine[0]["remote"], "volume only (no driver for this brand)")
        finally:
            other.close()
